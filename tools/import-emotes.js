'use strict';

const fs = require('node:fs');
const path = require('node:path');

const APP_ROOT = path.join(__dirname, '..');
const SOURCE = process.argv[2] ? path.resolve(process.argv[2]) : '';
const DEST = path.join(APP_ROOT, 'src', 'assets', 'emotes');
const MANIFEST = path.join(APP_ROOT, 'src', 'shared', 'emotes.js');

const CATEGORY_ORDER = ['character', 'ui', 'meme', 'prop'];
const CATEGORY_LABELS = {
  character: '角色',
  ui: 'UI',
  meme: '梗图',
  prop: '道具'
};

function fail(message) {
  console.error('import-emotes: ' + message);
  process.exit(1);
}

if (!SOURCE) {
  fail('usage: node tools/import-emotes.js <party-animals-emotes 目录>');
}

const metadataPath = path.join(SOURCE, 'metadata.json');
if (!fs.existsSync(metadataPath)) {
  fail('缺少 metadata.json：' + metadataPath);
}

const metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'));
const emotes = Array.isArray(metadata.emotes) ? metadata.emotes : [];
if (!emotes.length) fail('metadata.json 中没有 emotes');

const known = new Set(CATEGORY_ORDER);
const ids = new Set();
for (const e of emotes) {
  if (!e || typeof e.id !== 'string' || !/^[a-z0-9-]+$/.test(e.id)) {
    fail('非法表情 id：' + JSON.stringify(e && e.id));
  }
  if (ids.has(e.id)) fail('重复表情 id：' + e.id);
  ids.add(e.id);
  if (!known.has(e.category)) fail(`${e.id} 的分类未知：${e.category}`);
  if (!['gif', 'png'].includes(e.format)) fail(`${e.id} 的格式不支持：${e.format}`);
  const srcFile = path.join(SOURCE, e.file);
  if (!fs.existsSync(srcFile)) fail(`${e.id} 缺少原图：${e.file}`);
  if (e.format === 'gif') {
    if (!e.framesDir) fail(`${e.id} 缺少 framesDir`);
    const firstFrame = path.join(SOURCE, e.framesDir, 'frame-000.png');
    if (!fs.existsSync(firstFrame)) fail(`${e.id} 缺少首帧：${e.framesDir}/frame-000.png`);
  }
}

const ordered = emotes
  .map((e, index) => ({ e, index }))
  .sort((a, b) => {
    const ca = CATEGORY_ORDER.indexOf(a.e.category);
    const cb = CATEGORY_ORDER.indexOf(b.e.category);
    return ca === cb ? a.index - b.index : ca - cb;
  })
  .map(({ e }) => e);

fs.rmSync(DEST, { recursive: true, force: true });
fs.mkdirSync(path.join(DEST, 'thumb'), { recursive: true });

const list = [];
for (const e of ordered) {
  const file = path.basename(e.file);
  const thumb = `thumb/${e.id}.png`;
  fs.copyFileSync(path.join(SOURCE, e.file), path.join(DEST, file));

  const firstFrame = e.format === 'gif'
    ? path.join(SOURCE, e.framesDir, 'frame-000.png')
    : path.join(SOURCE, e.file);
  fs.copyFileSync(firstFrame, path.join(DEST, 'thumb', `${e.id}.png`));

  list.push({
    id: e.id,
    name: e.name,
    nameZh: e.nameZh,
    category: e.category,
    file,
    thumb,
    format: e.format,
    width: e.width,
    height: e.height,
    durationMs: e.durationMs || 0
  });
}

const noticePath = path.join(SOURCE, 'NOTICE.md');
if (!fs.existsSync(noticePath)) fail('缺少源 NOTICE.md');
const notice = [
  '> 本目录由 meeting-friends 的 `tools/import-emotes.js` 从 party-animals-emotes 素材库导入。',
  '> 素材版权归 Recreate Games / Source Technology 所有，仅限个人、非商业用途；如权利方要求请立即移除。',
  '',
  fs.readFileSync(noticePath, 'utf8')
].join('\n');
fs.writeFileSync(path.join(DEST, 'NOTICE.md'), notice, 'utf8');

const categories = CATEGORY_ORDER
  .map((key) => ({ key, label: CATEGORY_LABELS[key], count: list.filter((e) => e.category === key).length }))
  .filter((c) => c.count > 0);

const manifest = `// Generated by tools/import-emotes.js. Do not edit by hand.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Emotes = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  const list = ${JSON.stringify(list, null, 2)};
  const byId = {};
  for (const e of list) byId[e.id] = e;
  const ids = list.map((e) => e.id);
  const categories = ${JSON.stringify(categories, null, 2)};
  const url = (e) => '../../assets/emotes/' + e.file;
  const thumbUrl = (e) => '../../assets/emotes/' + e.thumb;
  return { list, byId, ids, categories, url, thumbUrl };
});
`;
fs.writeFileSync(MANIFEST, manifest, 'utf8');

console.log(`导入 ${list.length} 个表情 → ${path.relative(APP_ROOT, DEST)}`);
for (const c of categories) console.log(`- ${c.key}: ${c.count}`);
console.log(`清单 → ${path.relative(APP_ROOT, MANIFEST)}`);
